def generate_usernames(
    style: str, count: int, taken: Set[str], rng: random.Random
) -> List[str]:
    """生成 count 个不与 taken 冲突的用户名。style: "npc" | "lowkey" | "phrase"。"""
    out: List[str] = []
    guard = 0
    while len(out) < count:
        guard += 1
        if guard > count * 200:
            raise RuntimeError("用户名生成多次碰撞，请扩充词库或减少数量")
        if style == "npc":
            name = f"NPC·{rng.choice(_NPC_ROLES)}·{rng.randint(1, 99):02d}"
        elif style == "phrase":
            adv = rng.choice(_PHRASE_ADV) if rng.random() < 0.5 else ""
            name = (
                f"{rng.choice(_PHRASE_ADJ)}的{rng.choice(_PHRASE_NOUN)}"
                f"{adv}{rng.choice(_PHRASE_VERB)}"
            )
        else:
            name = f"{rng.choice(_LOWKEY_HEADS)}{rng.choice(_LOWKEY_TAILS)}"
            if rng.random() < 0.45:
                name += str(rng.randint(2, 9999))
        if name in taken:
            continue
        taken.add(name)
        out.append(name)
    return out
